-- Что на самом деле присылает Buy Me a Coffee.
--
-- Эти запросы ничего не меняют — только читают. Выполнять в SQL-редакторе
-- Supabase, по одному.
--
-- Зачем. `api/billing/buymeacoffee` не разбирает тело платежа по жёсткой
-- схеме: форма payload у BMC отличается от события к событию, и строгий
-- парсер потерял бы настоящий платёж в день, когда они переименуют ключ.
-- Поэтому каждое тело целиком сохраняется в `payment_events`, и единственный
-- способ узнать, что там лежит на самом деле — посмотреть.
--
-- Главный вопрос, на который отвечают эти запросы: **присылает ли BMC почту
-- покупателя**. Если да — платёж сопоставляется с заявкой по ней. Если нет,
-- всё держится на совпадении по времени (единственная заявка, открытая за
-- последние 20 минут), а это работает, пока двое не покупают одновременно.

-- ───────────────────────────────────────────────────────────────────────────
-- 1. Последние доставки: что мы из них вытащили.
--
-- Пустой `email` в строке, где `amount` заполнен, и означает ту самую
-- проблему: деньги видим, а кому они принадлежат — нет.
-- ───────────────────────────────────────────────────────────────────────────
select
  received_at,
  event_type,
  email,
  amount,
  currency,
  matched,
  request_id     as заявка_на_рассылку,
  cv_purchase_id as покупка_word
from payment_events
order by received_at desc
limit 20;

-- ───────────────────────────────────────────────────────────────────────────
-- 2. Какие ключи вообще приходят в теле. Это и есть ответ про почту:
--    ищите в выдаче что-то вроде email, buyer_email, supporter_email.
-- ───────────────────────────────────────────────────────────────────────────
select distinct jsonb_object_keys(payload) as key
from payment_events
order by key;

-- ───────────────────────────────────────────────────────────────────────────
-- 3. Одно тело целиком — когда надо увидеть вложенность, а не только верхний
--    уровень. У BMC полезное часто лежит внутри объекта `data`.
-- ───────────────────────────────────────────────────────────────────────────
select jsonb_pretty(payload)
from payment_events
order by received_at desc
limit 1;

-- ───────────────────────────────────────────────────────────────────────────
-- 4. Сколько платежей не удалось ни с чем сопоставить. Это не ошибка сама по
--    себе — человек мог заплатить с другого ящика, — но если таких много,
--    значит автоматика не срабатывает и люди остаются без того, что купили.
-- ───────────────────────────────────────────────────────────────────────────
select
  count(*)                                   as всего,
  count(*) filter (where matched)            as сопоставлено,
  count(*) filter (where not matched)        as осталось_вручную
from payment_events;

-- ───────────────────────────────────────────────────────────────────────────
-- 5. **Главный запрос.** Запрос 3 отдаёт всё тело одной ячейкой, а редактор
--    Supabase её обрезает — ровно на том месте, где начинается интересное.
--    Здесь каждый ключ из `data` — отдельная строка, поэтому обрезать нечего.
--    Берутся три последние доставки, а не одна: последней может оказаться
--    платёж за рассылку, а нужен тот, где покупали CV.
--
--    Что искать. Нужен ответ на вопрос из формы BMC («Ask a question»): если
--    покупатель вписал туда свою почту или имя, платёж можно сопоставлять
--    точно. Такой ответ приходит под каким-то из ключей вроде
--    `question`, `answer`, `support_note`, `message`, `supporter_name`,
--    `extra_question` — заранее неизвестно, под каким именно, поэтому смотрим
--    все.
-- ───────────────────────────────────────────────────────────────────────────
select
  e.received_at,
  d.key                  as ключ,
  left(d.value, 300)     as значение
from (
  select * from payment_events order by received_at desc limit 3
) e,
lateral jsonb_each_text(e.payload -> 'data') d
order by e.received_at desc, d.key;

-- ───────────────────────────────────────────────────────────────────────────
-- 6. Что именно купили. `extras[].id` — это номер товара из ссылки на оплату
--    (.../e/583093), и именно по нему код отличает выгрузку CV от пакета
--    рассылки, не угадывая по сумме.
--
--    Если у какой-то доставки `extras` пустой — значит BMC для этого типа
--    события товар не называет, и для неё по-прежнему работает старое
--    правило по цене.
-- ───────────────────────────────────────────────────────────────────────────
select
  e.received_at,
  e.event_type,
  e.email,
  e.amount,
  x.value ->> 'id'    as товар_id,
  x.value ->> 'title' as товар
from payment_events e
left join lateral jsonb_array_elements(e.payload -> 'data' -> 'extras') x on true
order by e.received_at desc
limit 20;

-- ───────────────────────────────────────────────────────────────────────────
-- 7. Все ключи `data`, какие вообще встречались, с примером значения. Шире
--    запроса 5: тот смотрит одну последнюю доставку, а разные типы событий у
--    BMC присылают разные поля, и нужный ключ может быть только в одном из них.
-- ───────────────────────────────────────────────────────────────────────────
select
  d.key                               as ключ,
  count(*)                            as доставок,
  left(max(d.value), 120)             as пример_значения
from payment_events e,
     lateral jsonb_each_text(e.payload -> 'data') d
group by d.key
order by d.key;
