-- Что на самом деле присылает Buy Me a Coffee.
--
-- Эти запросы ничего не меняют — только читают. Выполнять в SQL-редакторе
-- Supabase, по одному.
--
-- Зачем. `api/billing/buymeacoffee` не разбирает тело платежа по жёсткой
-- схеме: форма payload у BMC отличается от события к событию, и строгий
-- парсер потерял бы настоящий платёж в день, когда они переименуют ключ.
-- Поэтому каждое тело целиком сохраняется в `payment_events`, и единственный
-- способ узнать, что там лежит на самом деле — посмотреть.
--
-- Главный вопрос, на который отвечают эти запросы: **присылает ли BMC почту
-- покупателя**. Если да — платёж сопоставляется с заявкой по ней. Если нет,
-- всё держится на совпадении по времени (единственная заявка, открытая за
-- последние 20 минут), а это работает, пока двое не покупают одновременно.

-- ───────────────────────────────────────────────────────────────────────────
-- 1. Последние доставки: что мы из них вытащили.
--
-- Пустой `email` в строке, где `amount` заполнен, и означает ту самую
-- проблему: деньги видим, а кому они принадлежат — нет.
-- ───────────────────────────────────────────────────────────────────────────
select
  received_at,
  event_type,
  email,
  amount,
  currency,
  matched,
  request_id     as заявка_на_рассылку,
  cv_purchase_id as покупка_word
from payment_events
order by received_at desc
limit 20;

-- ───────────────────────────────────────────────────────────────────────────
-- 2. Какие ключи вообще приходят в теле. Это и есть ответ про почту:
--    ищите в выдаче что-то вроде email, buyer_email, supporter_email.
-- ───────────────────────────────────────────────────────────────────────────
select distinct jsonb_object_keys(payload) as key
from payment_events
order by key;

-- ───────────────────────────────────────────────────────────────────────────
-- 3. Одно тело целиком — когда надо увидеть вложенность, а не только верхний
--    уровень. У BMC полезное часто лежит внутри объекта `data`.
-- ───────────────────────────────────────────────────────────────────────────
select jsonb_pretty(payload)
from payment_events
order by received_at desc
limit 1;

-- ───────────────────────────────────────────────────────────────────────────
-- 4. Сколько платежей не удалось ни с чем сопоставить. Это не ошибка сама по
--    себе — человек мог заплатить с другого ящика, — но если таких много,
--    значит автоматика не срабатывает и люди остаются без того, что купили.
-- ───────────────────────────────────────────────────────────────────────────
select
  count(*)                                   as всего,
  count(*) filter (where matched)            as сопоставлено,
  count(*) filter (where not matched)        as осталось_вручную
from payment_events;
