-- Разовый скрипт: вернуть на доску вакансии, которые погасил ночной крон
-- из-за даты выхода, уже прошедшей на момент импорта.
--
-- Контекст. `api/cron/close-expired-vacancies` выключает вакансию, у которой
-- joining_date старше 14 дней, и до правки #252 не смотрел на возраст самой
-- публикации. Парсеру велено читать «joining September» как первое число
-- месяца, поэтому пост, написанный в конце сентября, приезжал с датой
-- трёхнедельной давности — и гас в ближайшую ночь, всем импортированным
-- батчем сразу, потому что один исходный пост даёт одну дату всем рангам в нём.
--
-- Правка #252 чинит это вперёд: прошедшая дата при импорте пишется как NULL
-- (то есть ASAP), и крон не трогает публикации моложе 14 дней. Но у уже
-- погасших строк в базе лежит та же старая дата, поэтому сами они не вернутся,
-- а если включить их тумблером — погаснут снова.
--
-- Этот скрипт обнуляет у них дату выхода и поднимает is_active. NULL здесь не
-- потеря данных, а верное прочтение: агентство набирало людей тогда и, судя по
-- тому что объявление висело, набирает сейчас — «ASAP» описывает это точнее,
-- чем дата, которая прошла.
--
-- ВАЖНО: запускать ПОСЛЕ того, как #252 уехал в production. Иначе крон погасит
-- их следующей же ночью, потому что условие по created_at ещё не действует.
--
-- Выполнять в SQL-редакторе Supabase по шагам: сначала 1, потом 2, потом 3.

-- ───────────────────────────────────────────────────────────────────────────
-- Шаг 1. Посмотреть, что скрипт тронет. Ничего не меняет.
--
-- Колонка updated_at здесь не для красоты: крон ходит в 01:00 UTC, поэтому у
-- строк, выключенных именно им, время правки стоит около 01:0x. Если в выдаче
-- попадётся вакансия с другим временем — её, скорее всего, выключили руками, и
-- поднимать её не надо (как сузить выборку — в шаге 3).
-- ───────────────────────────────────────────────────────────────────────────
select
  v.id,
  c.name                      as company,
  v.title,
  v.rank,
  v.joining_date,
  v.created_at::date          as posted,
  v.updated_at                as closed_at,
  v.is_imported
from vacancies v
left join companies c on c.id = v.company_id
where v.is_active = false
  and v.joining_date is not null
  and v.joining_date < current_date
order by v.updated_at desc, c.name, v.title;

-- ───────────────────────────────────────────────────────────────────────────
-- Шаг 2. Сколько строк это всего и как они разложены по времени выключения.
-- ───────────────────────────────────────────────────────────────────────────
select
  date_trunc('hour', updated_at) as closed_hour,
  count(*)                       as rows,
  count(*) filter (where is_imported) as imported
from vacancies
where is_active = false
  and joining_date is not null
  and joining_date < current_date
group by 1
order by 1 desc;

-- ───────────────────────────────────────────────────────────────────────────
-- Шаг 3. Поднять. Выполнять, только посмотрев выдачу шага 1.
--
-- Ограничение is_imported = true стоит намеренно: вакансию, которую компания
-- разместила и выключила сама через свой кабинет, мы возвращать не вправе.
--
-- Если в шаге 1 видно, что часть строк выключена не в 01:0x UTC, добавьте
-- к условию отсечку по времени, например:
--     and updated_at::time between '00:55' and '01:15'
-- ───────────────────────────────────────────────────────────────────────────
update vacancies
set joining_date = null,      -- ASAP: то же, что теперь пишет импорт
    is_active    = true
where is_active = false
  and is_imported = true
  and joining_date is not null
  and joining_date < current_date
returning id, title, company_id;

